def calculate_love_match(
    user_a_scores: dict[str, float], user_b_scores: dict[str, float]
) -> dict[str, Any]:
    """计算两位用户的亲密关系匹配度（修复通胀：起始分75分）"""
    match_score = 75.0  # 起始分降到75分，避免通胀
    dimension_analysis = {}

    # EI维度: 互补
    ei_diff = abs(user_a_scores.get("ei", 50) - user_b_scores.get("ei", 50))
    if ei_diff > 50:
        match_score += 10  # 极度互补奖励
        dimension_analysis["ei"] = "社交能量完美互补: 一个充电宝配一个耗电怪，绝配!"
    elif ei_diff < 15:
        match_score -= 12  # 同质化扣分
        dimension_analysis["ei"] = "社交能量同质化，需要互相给空间"
    else:
        dimension_analysis["ei"] = "社交能量适中互补"

    # SN维度: 同频（冲突狠狠扣分）
    sn_diff = abs(user_a_scores.get("sn", 50) - user_b_scores.get("sn", 50))
    if sn_diff > 60:
        match_score -= 20  # 三观冲突狠狠扣分
        dimension_analysis["sn"] = "三观频道冲突: 务实派vs浪漫派，会鸡同鸭讲"
    elif sn_diff < 20:
        match_score += 8
        dimension_analysis["sn"] = "灵魂共鸣: 关注焦点同频"
    else:
        dimension_analysis["sn"] = "关注焦点基本同频"

    # TF维度: 轻微互补
    a_is_t = user_a_scores.get("tf", 50) >= 50
    b_is_t = user_b_scores.get("tf", 50) >= 50
    if a_is_t != b_is_t:
        match_score += 10
        dimension_analysis["tf"] = "决策方式完美互补: 一个理智派一个感性派，绝配!"
    else:
        # 两个极端T或极端F要扣分
        a_tf = user_a_scores.get("tf", 50)
        b_tf = user_b_scores.get("tf", 50)
        if a_tf > 80 and b_tf > 80:
            match_score -= 15
            dimension_analysis["tf"] = "双理智派冲突: 吵架变成辩论赛，谁都不肯先软化"
        elif a_tf < 20 and b_tf < 20:
            match_score -= 15
            dimension_analysis["tf"] = "双感性派冲突: 吵架洪水漫溢，没人理性解决"
        else:
            dimension_analysis["tf"] = "决策方式基本同频"

    # JP维度: 中度互补
    a_is_j = user_a_scores.get("jp", 50) >= 50
    b_is_j = user_b_scores.get("jp", 50) >= 50
    if a_is_j != b_is_j:
        match_score += 8
        dimension_analysis["jp"] = "生活节奏互补: 一个计划派一个随性派，很舒服"
    else:
        a_jp = user_a_scores.get("jp", 50)
        b_jp = user_b_scores.get("jp", 50)
        if a_jp > 80 and b_jp > 80:
            match_score -= 10
            dimension_analysis["jp"] = "双计划派冲突: 约会牙膏怎么挤都能吵架"
        elif a_jp < 20 and b_jp < 20:
            match_score -= 10
            dimension_analysis["jp"] = "双随性派冲突: 约会永远在迟到"
        else:
            dimension_analysis["jp"] = "生活节奏基本兼容"

    final_score = max(0, min(100, match_score))

    if final_score >= 85:
        analysis = "🌟 恋爱匹配度极高，你们是天作之合!"
    elif final_score >= 70:
        analysis = "💕 恋爱匹配度良好，你们很适合在一起"
    elif final_score >= 50:
        analysis = "⚖️ 恋爱匹配度中等，需要多磨合多沟通"
    else:
        analysis = "⚠️ 恋爱匹配度较低，你们需要努力才能走到一起"

    return {
        "score": round(final_score, 1),
        "analysis": analysis,
        "dimension_analysis": dimension_analysis,
    }


