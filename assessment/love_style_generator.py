def is_balanced_master(scores: dict[str, float]) -> bool:
    """检测是否为端水大师"""
    for dimension in DIMENSIONS:
        score = scores.get(dimension, 50)
        if score < BALANCED_MASTER_TAG["threshold"]["min"] or score > BALANCED_MASTER_TAG["threshold"]["max"]:
            return False
    return True


def get_labels(scores: dict[str, float]) -> list[str]:
    """根据分数生成标签列表"""
    type_code = _type_code_from_scores(scores)
    type_info = get_type_info(type_code)
    labels = [type_info["nickname"]] + type_info["tags"][:5]
    return labels[:6]


