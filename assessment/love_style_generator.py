def _type_code_from_scores(scores: dict[str, float]) -> str:
    """根据分数生成 MBTI 类型代码"""
    return "".join([
        "E" if scores.get("ei", 50) >= 50 else "I",
        "S" if scores.get("sn", 50) >= 50 else "N",
        "T" if scores.get("tf", 50) >= 50 else "F",
        "J" if scores.get("jp", 50) >= 50 else "P",
    ])


