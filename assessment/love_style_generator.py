def _format_xiaoya_dimension_focus(scores: dict[str, float]) -> list[str]:
    lines = []
    for dimension in ["ei", "sn", "tf", "jp"]:
        bucket = "high" if scores.get(dimension, 50) >= 50 else "low"
        text = XIAOYA_DIMENSION_TRANSLATIONS[dimension][bucket]["focus"]
        lines.append(text)
    return lines


def _format_xiaoya_relationship_focus(scores: dict[str, float]) -> list[str]:
    lines = []
    for dimension in ["ei", "sn", "tf", "jp"]:
        bucket = "high" if scores.get(dimension, 50) >= 50 else "low"
        lines.append(XIAOYA_DIMENSION_TRANSLATIONS[dimension][bucket]["relationship"])
    return lines


def _build_xiaoya_match_hints(type_code: str) -> list[str]:
    hints: list[str] = []
    config = XIAOYA_MATCH_HINTS.get(type_code)
    if not config:
        return hints

    easier = config.get("easier")
    if isinstance(easier, tuple) and len(easier) == 2:
        hints.append(f"相对更容易聊得来的，常常会是像 **{easier[0]}** 这样的类型，因为 ~~{easier[1]}~~")

    harder = config.get("harder")
    if isinstance(harder, tuple) and len(harder) == 2:
        hints.append(f"相对更需要磨合的，常常会是像 **{harder[0]}** 这样的类型，因为 ~~{harder[1]}~~")

    return hints


