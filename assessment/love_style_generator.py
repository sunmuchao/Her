def _resolve_preference_bucket(dimension: str, score: float) -> dict[str, str]:
    preference = OFFICIAL_DIMENSION_PREFERENCES[dimension]
    return preference["high"] if score >= 50 else preference["low"]


def _build_official_dimension_summary(scores: dict[str, float]) -> str:
    dimension_order = ["ei", "sn", "tf", "jp"]
    lines = []
    for dimension in dimension_order:
        info = _resolve_preference_bucket(dimension, scores.get(dimension, 50))
        lines.append(f"{info['letter']} ({info['name']}): {info['plain']}")
    return "\n".join(lines)


def _build_relationship_extension(scores: dict[str, float]) -> str:
    relationship_lines = []
    for dimension in ["ei", "sn", "tf", "jp"]:
        info = _resolve_preference_bucket(dimension, scores.get(dimension, 50))
        relationship_lines.append(info["relationship"])
    return "\n".join(f"- {line}" for line in relationship_lines)


