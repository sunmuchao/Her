def make_photo_rows(profile):
    created_at = profile["created_at"]
    updated_at = profile["updated_at"]
    rows = [
        {
            "profile_id": profile["id"],
            "photo_url": profile["avatar_url"],
            "photo_type": "avatar",
            "sort_order": 0,
            "is_primary": 1,
            "created_at": created_at,
            "updated_at": updated_at,
        }
    ]
    for idx in range(1, int(profile["photo_count"]) + 1):
        rows.append(
            {
                "profile_id": profile["id"],
                "photo_url": f"https://img.her.local/seed/{profile['id']}/{idx}.jpg",
                "photo_type": "gallery",
                "sort_order": idx,
                "is_primary": 0,
                "created_at": created_at,
                "updated_at": updated_at,
            }
        )
    return rows


