def ensure_columns(conn, table_name):
    with conn.cursor() as cursor:
        cursor.execute(f"SHOW COLUMNS FROM `{table_name}`")
        existing = {row[0] for row in cursor.fetchall()}
        for column, column_type in {**ALL_NEW_COLUMNS, **STRUCTURED_COLUMN_TYPES}.items():
            if column not in existing:
                cursor.execute(f"ALTER TABLE `{table_name}` ADD COLUMN `{column}` {column_type} NULL")


def upsert_profiles(conn, table_name, profiles):
    placeholders = ", ".join(["%s"] * len(PROFILE_COLUMNS))
    column_sql = ", ".join(f"`{column}`" for column in PROFILE_COLUMNS)
    update_sql = ", ".join(
        f"`{column}`=VALUES(`{column}`)" for column in PROFILE_COLUMNS if column != "id"
    )
    sql = (
        f"INSERT INTO `{table_name}` ({column_sql}) VALUES ({placeholders}) "
        f"ON DUPLICATE KEY UPDATE {update_sql}"
    )
    rows = [tuple(profile[column] for column in PROFILE_COLUMNS) for profile in profiles]
    with conn.cursor() as cursor:
        cursor.executemany(sql, rows)


def replace_photos(conn, table_name, profiles):
    profile_ids = [profile["id"] for profile in profiles]
    delete_placeholders = ", ".join(["%s"] * len(profile_ids))
    photo_rows = []
    for profile in profiles:
        photo_rows.extend(make_photo_rows(profile))
    insert_columns = [
        "profile_id",
        "photo_url",
        "photo_type",
        "sort_order",
        "is_primary",
        "created_at",
        "updated_at",
    ]
    insert_sql = (
        f"INSERT INTO `{table_name}` ({', '.join(f'`{column}`' for column in insert_columns)}) "
        f"VALUES ({', '.join(['%s'] * len(insert_columns))})"
    )
    with conn.cursor() as cursor:
        cursor.execute(
            f"DELETE FROM `{table_name}` WHERE `profile_id` IN ({delete_placeholders})",
            profile_ids,
        )
        cursor.executemany(
            insert_sql,
            [tuple(row[column] for column in insert_columns) for row in photo_rows],
        )


def main():
    args = parse_args()
    try:
        import pymysql
    except ImportError as exc:  # pragma: no cover
        raise SystemExit("PyMySQL is required to seed gap profiles.") from exc

    profiles = build_profiles()
    conn = pymysql.connect(
        host=args.host,
        port=args.port,
        user=args.user,
        password=args.password,
        database=args.database,
        charset=args.charset,
        autocommit=False,
    )
    try:
        ensure_columns(conn, args.table)
        upsert_profiles(conn, args.table, profiles)
        replace_photos(conn, args.photos_table, profiles)
        conn.commit()
        print(f"Seeded {len(profiles)} curated profiles into {args.database}.{args.table}")
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


if __name__ == "__main__":
    main()
